        private static Font _font;

        private static Font DefaultFont()
        {
            if (_font != null) return _font;

            // Unity renamed the built-in font part way through the 2022 cycle.
            _font = Resources.GetBuiltinResource<Font>("LegacyRuntime.ttf")
                    ?? Resources.GetBuiltinResource<Font>("Arial.ttf");

            return _font;
        }

        private static void BuildHud()
        {
            var eventSystem = new GameObject("EventSystem");
            eventSystem.AddComponent<EventSystem>();
            eventSystem.AddComponent<StandaloneInputModule>();

            var canvasObject = new GameObject("HUD");
            var canvas = canvasObject.AddComponent<Canvas>();
            canvas.renderMode = RenderMode.ScreenSpaceOverlay;

            var scaler = canvasObject.AddComponent<CanvasScaler>();
            scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
            scaler.referenceResolution = new Vector2(1920f, 1080f);
            scaler.matchWidthOrHeight = 0.5f;

            canvasObject.AddComponent<GraphicRaycaster>();

            var hud = canvasObject.AddComponent<GameHUD>();

            // --- top bar ---------------------------------------------------
            Text levelText = Label(canvasObject, "LevelText", new Vector2(0f, 1f), new Vector2(0f, 1f),
                                   new Vector2(40f, -40f), new Vector2(600f, 60f),
                                   "1. Rooftops", 40, TextAnchor.UpperLeft);

            Text timeText = Label(canvasObject, "TimeText", new Vector2(0.5f, 1f), new Vector2(0.5f, 1f),
                                  new Vector2(0f, -40f), new Vector2(400f, 60f),
                                  "00:00.00", 44, TextAnchor.UpperCenter);

            Text pickupText = Label(canvasObject, "PickupText", new Vector2(1f, 1f), new Vector2(1f, 1f),
                                    new Vector2(-40f, -40f), new Vector2(300f, 60f),
                                    "0", 44, TextAnchor.UpperRight);

            // --- progress bar ----------------------------------------------
            GameObject track = Panel(canvasObject, "ProgressTrack", new Color(1f, 1f, 1f, 0.15f));
            RectTransform trackRect = track.GetComponent<RectTransform>();
            trackRect.anchorMin = new Vector2(0.5f, 1f);
            trackRect.anchorMax = new Vector2(0.5f, 1f);
            trackRect.pivot = new Vector2(0.5f, 1f);
            trackRect.anchoredPosition = new Vector2(0f, -110f);
            trackRect.sizeDelta = new Vector2(900f, 14f);

            GameObject fillObject = Panel(track, "ProgressFill", new Color(0.45f, 0.95f, 0.7f, 0.95f));
            RectTransform fillRect = fillObject.GetComponent<RectTransform>();
            fillRect.anchorMin = Vector2.zero;
            fillRect.anchorMax = Vector2.one;
            fillRect.offsetMin = Vector2.zero;
            fillRect.offsetMax = Vector2.zero;

            var fillImage = fillObject.GetComponent<Image>();
            fillImage.type = Image.Type.Filled;
            fillImage.fillMethod = Image.FillMethod.Horizontal;
            fillImage.fillAmount = 0f;

            // --- panels ----------------------------------------------------
            GameObject ready = Overlay(canvasObject, "ReadyPanel", new Color(0f, 0f, 0f, 0.35f));
            Label(ready, "ReadyTitle", CentreAnchor, CentreAnchor, new Vector2(0f, 90f),
                  new Vector2(1200f, 90f), "TAP TO START", 72, TextAnchor.MiddleCenter);
            Text readyHint = Label(ready, "ReadyHint", CentreAnchor, CentreAnchor, new Vector2(0f, -10f),
                                   new Vector2(1200f, 120f), "", 36, TextAnchor.MiddleCenter);

            GameObject death = Overlay(canvasObject, "DeathPanel", new Color(0.25f, 0f, 0f, 0.55f));
            Label(death, "DeathTitle", CentreAnchor, CentreAnchor, new Vector2(0f, 120f),
                  new Vector2(1200f, 90f), "RUN OVER", 72, TextAnchor.MiddleCenter);
            Text deathReason = Label(death, "DeathReason", CentreAnchor, CentreAnchor, new Vector2(0f, 40f),
                                     new Vector2(1200f, 60f), "", 36, TextAnchor.MiddleCenter);
            Button restart = MakeButton(death, "RestartButton", new Vector2(0f, -80f), "Retry");

            GameObject finish = Overlay(canvasObject, "FinishPanel", new Color(0f, 0.2f, 0.1f, 0.55f));
            Label(finish, "FinishTitle", CentreAnchor, CentreAnchor, new Vector2(0f, 150f),
                  new Vector2(1200f, 90f), "LEVEL CLEAR", 72, TextAnchor.MiddleCenter);
            Text finishSummary = Label(finish, "FinishSummary", CentreAnchor, CentreAnchor, new Vector2(0f, 50f),
                                       new Vector2(1200f, 120f), "", 36, TextAnchor.MiddleCenter);
            Button next = MakeButton(finish, "NextButton", new Vector2(-180f, -90f), "Next Level");
            Button retry = MakeButton(finish, "RetryButton", new Vector2(180f, -90f), "Replay");

            GameObject pause = Overlay(canvasObject, "PausePanel", new Color(0f, 0f, 0f, 0.6f));
            Label(pause, "PauseTitle", CentreAnchor, CentreAnchor, new Vector2(0f, 90f),
                  new Vector2(1200f, 90f), "PAUSED", 72, TextAnchor.MiddleCenter);
            Button resume = MakeButton(pause, "ResumeButton", new Vector2(0f, -40f), "Resume");

            ready.SetActive(false);
            death.SetActive(false);
            finish.SetActive(false);
            pause.SetActive(false);

            // --- wire it up ------------------------------------------------
            EditorUtil.SetObject(hud, "levelText", levelText);
            EditorUtil.SetObject(hud, "timeText", timeText);
            EditorUtil.SetObject(hud, "pickupText", pickupText);
            EditorUtil.SetObject(hud, "progressFill", fillImage);
            EditorUtil.SetObject(hud, "progressTrack", trackRect);

            EditorUtil.SetObject(hud, "readyPanel", ready);
            EditorUtil.SetObject(hud, "readyHintText", readyHint);
            EditorUtil.SetObject(hud, "deathPanel", death);
            EditorUtil.SetObject(hud, "deathReasonText", deathReason);
            EditorUtil.SetObject(hud, "finishPanel", finish);
            EditorUtil.SetObject(hud, "finishSummaryText", finishSummary);
            EditorUtil.SetObject(hud, "pausePanel", pause);

            EditorUtil.SetObject(hud, "restartButton", restart);
            EditorUtil.SetObject(hud, "nextLevelButton", next);
            EditorUtil.SetObject(hud, "retryFromFinishButton", retry);
            EditorUtil.SetObject(hud, "resumeButton", resume);
        }

        private static readonly Vector2 CentreAnchor = new Vector2(0.5f, 0.5f);

        private static Text Label(GameObject parent, string name, Vector2 anchorMin, Vector2 anchorMax,
                                  Vector2 position, Vector2 size, string content, int fontSize,
                                  TextAnchor alignment)
        {
            var go = new GameObject(name);
            go.transform.SetParent(parent.transform, false);

            var rect = go.AddComponent<RectTransform>();
            rect.anchorMin = anchorMin;
            rect.anchorMax = anchorMax;
            rect.pivot = new Vector2(anchorMin.x, anchorMax.y);
            rect.anchoredPosition = position;
            rect.sizeDelta = size;

            var text = go.AddComponent<Text>();
            text.font = DefaultFont();
            text.text = content;
            text.fontSize = fontSize;
            text.alignment = alignment;
            text.color = Color.white;
            text.raycastTarget = false;
            text.horizontalOverflow = HorizontalWrapMode.Wrap;
            text.verticalOverflow = VerticalWrapMode.Overflow;

            return text;
        }

        private static GameObject Panel(GameObject parent, string name, Color colour)
        {
            var go = new GameObject(name);
            go.transform.SetParent(parent.transform, false);
            go.AddComponent<RectTransform>();

            var image = go.AddComponent<Image>();
            image.color = colour;
            image.raycastTarget = false;

            return go;
        }

        /// <summary>A full-screen panel used for the start, death and finish screens.</summary>
        private static GameObject Overlay(GameObject parent, string name, Color colour)
        {
            GameObject go = Panel(parent, name, colour);

            var rect = go.GetComponent<RectTransform>();
            rect.anchorMin = Vector2.zero;
            rect.anchorMax = Vector2.one;
            rect.offsetMin = Vector2.zero;
            rect.offsetMax = Vector2.zero;

            go.GetComponent<Image>().raycastTarget = true;
            return go;
        }

        private static Button MakeButton(GameObject parent, string name, Vector2 position, string label)
        {
            var go = new GameObject(name);
            go.transform.SetParent(parent.transform, false);

            var rect = go.AddComponent<RectTransform>();
            rect.anchorMin = CentreAnchor;
            rect.anchorMax = CentreAnchor;
            rect.pivot = CentreAnchor;
            rect.anchoredPosition = position;
            rect.sizeDelta = new Vector2(320f, 96f);

            var image = go.AddComponent<Image>();
            image.color = new Color(1f, 1f, 1f, 0.18f);

            var button = go.AddComponent<Button>();
            button.targetGraphic = image;

