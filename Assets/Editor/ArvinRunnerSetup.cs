        private static GameObject CreatePlayerPrefab(PlayerConfig config, SpriteAnimationSet animations)
        {
            var root = new GameObject("Player") { layer = GameLayers.Player };

            var body = root.AddComponent<Rigidbody2D>();
            body.gravityScale = config.riseGravity;
            body.freezeRotation = true;
            body.collisionDetectionMode = CollisionDetectionMode2D.Continuous;
            body.interpolation = RigidbodyInterpolation2D.Interpolate;

            const float height = 1.75f;
            const float width = 0.8f;

            var capsule = root.AddComponent<CapsuleCollider2D>();
            capsule.direction = CapsuleDirection2D.Vertical;
            capsule.size = new Vector2(width, height);
            capsule.offset = new Vector2(0f, height * 0.5f);   // pivot at the feet

            var material = new PhysicsMaterial2D("PlayerFrictionless") { friction = 0f, bounciness = 0f };
            EditorUtil.CreateAsset(material, $"{DataFolder}/PlayerFrictionless.physicsMaterial2D");
            capsule.sharedMaterial = material;

            var visual = new GameObject("Visual") { layer = GameLayers.Player };
            visual.transform.SetParent(root.transform, false);

            Sprite runner = ArtImport.Load("runner");

            // The imported runner has a bottom-centre pivot, so it sits at the
            // capsule's base. The generated placeholder is centred, so it needs
            // lifting by half its height.
            visual.transform.localPosition = runner != null
                ? Vector3.zero
                : new Vector3(0f, height * 0.5f, 0f);

            var renderer = visual.AddComponent<SpriteRenderer>();
            renderer.sprite = runner ?? PlaceholderArt.Load("runner");
            renderer.sortingOrder = 20;

            var driver = visual.AddComponent<PlayerAnimatorDriver>();
            EditorUtil.SetObject(driver, "animationSet", animations);

            root.AddComponent<PlayerSensors>();

            var controller = root.AddComponent<PlayerController>();
            EditorUtil.SetObject(controller, "config", config);
            EditorUtil.SetObject(controller, "animator", driver);

            return SavePrefab(root, $"{PrefabFolder}/Player.prefab");
        }

        private static GameObject CreatePadPrefab()
        {
            var root = new GameObject("GroundPad") { layer = GameLayers.Ground };
            root.AddComponent<BoxCollider2D>();

            var visual = new GameObject("Visual") { layer = GameLayers.Ground };
            visual.transform.SetParent(root.transform, false);

            var renderer = visual.AddComponent<SpriteRenderer>();
            renderer.sprite = PlaceholderArt.Load("box");
            renderer.drawMode = SpriteDrawMode.Tiled;
            renderer.tileMode = SpriteTileMode.Continuous;
            renderer.color = new Color(0.20f, 0.21f, 0.30f);
            renderer.sortingOrder = 5;

            var strip = root.AddComponent<GroundStrip>();
            EditorUtil.SetObject(strip, "body", renderer);
            EditorUtil.SetObject(strip, "box", root.GetComponent<BoxCollider2D>());
            strip.Resize(20f, 3f);

            return SavePrefab(root, $"{PrefabFolder}/GroundPad.prefab");
        }

        private static GameObject CreateFinishPrefab()
        {
            var root = new GameObject("FinishLine");

            // A chequered banner on a pole, not a solid slab. The old green
            // block read as a wall to jump rather than the goal to run through.
            var pole = new GameObject("Pole");
            pole.transform.SetParent(root.transform, false);
            pole.transform.localPosition = new Vector3(0f, 0f, 0f);

            var poleRenderer = pole.AddComponent<SpriteRenderer>();
            poleRenderer.sprite = PlaceholderArt.Load("box");
            poleRenderer.drawMode = SpriteDrawMode.Tiled;
            poleRenderer.tileMode = SpriteTileMode.Continuous;
            poleRenderer.size = new Vector2(0.18f, 6f);
            poleRenderer.color = new Color(0.85f, 0.87f, 0.92f, 0.9f);
            poleRenderer.sortingOrder = 11;

            var banner = new GameObject("Banner");
            banner.transform.SetParent(root.transform, false);
            banner.transform.localPosition = new Vector3(0.75f, 2.1f, 0f);

            var renderer = banner.AddComponent<SpriteRenderer>();
            renderer.sprite = PlaceholderArt.Load("finish");
            renderer.drawMode = SpriteDrawMode.Tiled;
            renderer.tileMode = SpriteTileMode.Continuous;
            renderer.size = new Vector2(1.5f, 0.9f);
            renderer.color = Color.white;
            renderer.sortingOrder = 12;

            var box = root.AddComponent<BoxCollider2D>();
            box.size = new Vector2(1.2f, 8f);
            box.isTrigger = true;

            root.AddComponent<FinishLine>();

            return SavePrefab(root, $"{PrefabFolder}/FinishLine.prefab");
        }

        private static GameObject CreateKillZonePrefab()
        {
            var root = new GameObject("KillZone");

            var box = root.AddComponent<BoxCollider2D>();
            box.size = new Vector2(400f, 4f);
            box.isTrigger = true;

            root.AddComponent<KillZone>();

            return SavePrefab(root, $"{PrefabFolder}/KillZone.prefab");
        }

        private static GameObject SavePrefab(GameObject root, string path)
        {
            EditorUtil.EnsureFolder(System.IO.Path.GetDirectoryName(path)?.Replace('\\', '/'));
            GameObject prefab = PrefabUtility.SaveAsPrefabAsset(root, path);
            Object.DestroyImmediate(root);
            return prefab;
        }

