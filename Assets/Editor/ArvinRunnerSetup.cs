        private static PlayerConfig CreatePlayerConfig()
        {
            var config = ScriptableObject.CreateInstance<PlayerConfig>();
            return EditorUtil.CreateAsset(config, $"{DataFolder}/PlayerConfig.asset");
        }

        /// <summary>
        /// An animation set with one empty slot per state, pre-filled with the
        /// placeholder runner so something shows up straight away.
        /// </summary>
        private static SpriteAnimationSet CreateAnimationSet()
        {
            var set = ScriptableObject.CreateInstance<SpriteAnimationSet>();

            // The hand-made runner if it has been imported, otherwise the
            // generated silhouette.
            Sprite runner = ArtImport.Load("runner") ?? PlaceholderArt.Load("runner");

            set.fallback = new SpriteAnimationClip
            {
                anim = PlayerAnim.Idle,
                frames = new[] { runner },
                fps = 1f,
                loop = true
            };

            var values = System.Enum.GetValues(typeof(PlayerAnim));
            var clips = new List<SpriteAnimationClip>();

            foreach (PlayerAnim anim in values)
            {
                clips.Add(new SpriteAnimationClip
                {
                    anim = anim,
                    frames = new[] { runner },   // replace with your own frames
                    fps = 12f,
                    loop = anim == PlayerAnim.Idle || anim == PlayerAnim.Run || anim == PlayerAnim.WallRun
                });
            }

            set.clips = clips.ToArray();
            return EditorUtil.CreateAsset(set, $"{DataFolder}/PlayerAnimations.asset");
        }

        private static ParallaxTheme CreateTheme(string assetName, Color sky, Color tint)
        {
            var theme = ScriptableObject.CreateInstance<ParallaxTheme>();
            theme.skyColour = sky;

            theme.layers = new[]
            {
                new ParallaxLayerDef
                {
                    name = "Sky", sprite = PlaceholderArt.Load("sky"),
                    parallax = 0f, verticalParallax = 0.9f, yOffset = 0f,
                    sortingOrder = -300, tint = tint, heightOverride = 30f
                },
                new ParallaxLayerDef
                {
                    name = "Far", sprite = PlaceholderArt.Load("skyline_far"),
                    parallax = 0.25f, verticalParallax = 0.75f, yOffset = -2f,
                    sortingOrder = -200, tint = tint, autoScrollSpeed = 0.15f
                },
                new ParallaxLayerDef
                {
                    name = "Mid", sprite = PlaceholderArt.Load("skyline_mid"),
                    parallax = 0.5f, verticalParallax = 0.55f, yOffset = -4f,
                    sortingOrder = -150, tint = tint
                },
                new ParallaxLayerDef
                {
                    name = "Near", sprite = PlaceholderArt.Load("skyline_near"),
                    parallax = 0.75f, verticalParallax = 0.35f, yOffset = -7f,
                    sortingOrder = -100, tint = tint
                }
            };

            return EditorUtil.CreateAsset(theme, $"{DataFolder}/{assetName}.asset");
        }

