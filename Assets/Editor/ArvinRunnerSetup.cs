        private static void BuildScene(GameObject playerPrefab, GameObject padPrefab,
                                       GameObject finishPrefab, GameObject killZonePrefab,
                                       LevelSet campaign, ParallaxTheme theme)
        {
            var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);

            // --- camera ----------------------------------------------------
            var cameraObject = new GameObject("Main Camera") { tag = "MainCamera" };
            var camera = cameraObject.AddComponent<Camera>();
            camera.orthographic = true;
            camera.orthographicSize = 7.5f;
            camera.clearFlags = CameraClearFlags.SolidColor;
            camera.backgroundColor = theme.skyColour;
            camera.transform.position = new Vector3(0f, 3f, -10f);
            cameraObject.AddComponent<AudioListener>();

            var follow = cameraObject.AddComponent<CameraFollow>();

            // --- player ----------------------------------------------------
            var player = (GameObject)PrefabUtility.InstantiatePrefab(playerPrefab, scene);
            player.transform.position = new Vector3(0f, 2f, 0f);
            var controller = player.GetComponent<PlayerController>();

            EditorUtil.SetObject(follow, "target", player.transform);
            EditorUtil.SetObject(follow, "player", controller);

            // --- background ------------------------------------------------
            var backgroundObject = new GameObject("Background");
            var background = backgroundObject.AddComponent<ParallaxBackground>();
            EditorUtil.SetObject(background, "theme", theme);
            EditorUtil.SetObject(background, "camera", camera);

            // --- systems ---------------------------------------------------
            var systems = new GameObject("Game");
            systems.AddComponent<SwipeInput>();

            var builder = systems.AddComponent<LevelBuilder>();
            EditorUtil.SetObject(builder, "padPrefab", padPrefab.GetComponent<GroundStrip>());
            EditorUtil.SetObject(builder, "finishLinePrefab", finishPrefab.GetComponent<FinishLine>());
            EditorUtil.SetObject(builder, "killZonePrefab", killZonePrefab.GetComponent<KillZone>());

            var manager = systems.AddComponent<GameManager>();
            EditorUtil.SetObject(manager, "builder", builder);
            EditorUtil.SetObject(manager, "player", controller);
            EditorUtil.SetObject(manager, "cameraFollow", follow);
            EditorUtil.SetObject(manager, "background", background);
            EditorUtil.SetObject(manager, "campaign", campaign);

            // --- interface -------------------------------------------------
            BuildHud();

            EditorUtil.EnsureFolder("Assets/Scenes");
            EditorSceneManager.SaveScene(scene, ScenePath);
            AddSceneToBuildSettings(ScenePath);
        }

        private static void AddSceneToBuildSettings(string path)
        {
            var scenes = new List<EditorBuildSettingsScene>(EditorBuildSettings.scenes);

            foreach (EditorBuildSettingsScene existing in scenes)
                if (existing.path == path) return;

            scenes.Insert(0, new EditorBuildSettingsScene(path, true));
            EditorBuildSettings.scenes = scenes.ToArray();
        }

