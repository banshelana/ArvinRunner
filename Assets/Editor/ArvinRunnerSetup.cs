        private static LevelSet CreateLevels(LevelChunk[] chunks, ParallaxTheme night, ParallaxTheme dusk)
        {
            LevelChunk Find(string name)
            {
                foreach (LevelChunk c in chunks)
                    if (c != null && c.name == name) return c;

                Debug.LogWarning($"[ArvinRunner] Chunk '{name}' not found.");
                return null;
            }

            // Level 1 teaches one move at a time, with flat rooftop between each.
            LevelDefinition one = Sequenced(1, "First Steps",
                "Swipe up to jump. Swipe up again in the air for a double jump.",
                night, 42f,
                Find("Chunk_Flat"), Find("Chunk_Cones"), Find("Chunk_Skip"),
                Find("Chunk_SlideGate"), Find("Chunk_Gap"), Find("Chunk_Flat"));

            LevelDefinition two = Sequenced(2, "Rooftops",
                "Swipe down to slide. Land hard and you will roll.",
                night, 60f,
                Find("Chunk_Barriers"), Find("Chunk_Condensers"), Find("Chunk_Spikes"),
                Find("Chunk_WideGap"), Find("Chunk_StepsDown"), Find("Chunk_Flat"));

            LevelDefinition three = Sequenced(3, "Construction",
                "Jump into a wall to run up it, then grab the ledge.",
                dusk, 80f,
                Find("Chunk_StreetWorks"), Find("Chunk_Collapsing"), Find("Chunk_WallClimb"),
                Find("Chunk_Crates"), Find("Chunk_Trampoline"), Find("Chunk_Flat"));

            // Levels 4 and 5 are assembled from a pool - fast to make, fixed seed
            // so the layout is identical on every attempt.
            LevelDefinition four = Assembled(4, "Skyline", "Watch the beam rhythm before you commit.",
                dusk, 90f, chunks, 380f, seed: 4471,
                curve: AnimationCurve.Linear(0f, 2f, 1f, 4f));

            LevelDefinition five = Assembled(5, "Storm", "The wind will cut your jump short. Commit early.",
                night, 120f, chunks, 480f, seed: 8823,
                curve: AnimationCurve.EaseInOut(0f, 3f, 1f, 5f));

            var campaign = ScriptableObject.CreateInstance<LevelSet>();
            campaign.levels = new[] { one, two, three, four, five };
            return EditorUtil.CreateAsset(campaign, $"{DataFolder}/Campaign.asset");
        }

        private static LevelDefinition Sequenced(int number, string title, string hint,
                                                 ParallaxTheme theme, float parTime,
                                                 params LevelChunk[] order)
        {
            var level = ScriptableObject.CreateInstance<LevelDefinition>();
            level.levelNumber = number;
            level.displayName = title;
            level.hint = hint;
            level.mode = LevelDefinition.BuildMode.Sequenced;
            level.sequence = order;
            level.theme = theme;
            level.parTime = parTime;

            return EditorUtil.CreateAsset(level, $"{LevelFolder}/Level_{number:00}.asset");
        }

        private static LevelDefinition Assembled(int number, string title, string hint,
                                                 ParallaxTheme theme, float parTime,
                                                 LevelChunk[] pool, float length, int seed,
                                                 AnimationCurve curve)
        {
            var level = ScriptableObject.CreateInstance<LevelDefinition>();
            level.levelNumber = number;
            level.displayName = title;
            level.hint = hint;
            level.mode = LevelDefinition.BuildMode.Assembled;
            level.pool = pool;
            level.targetLength = length;
            level.seed = seed;
            level.difficultyCurve = curve;
            level.theme = theme;
            level.parTime = parTime;

            return EditorUtil.CreateAsset(level, $"{LevelFolder}/Level_{number:00}.asset");
        }

